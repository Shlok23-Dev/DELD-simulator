import { describe, it, expect } from 'vitest';
import { runCircuitSimulation } from './circuitEngine';
import { REFERENCE_CIRCUITS } from '../data/referenceCircuits';
import { PRACTICALS } from '../data/practicals';

describe('Practical 1: Binary to Gray Reference Circuit Verification', () => {
  const ref = REFERENCE_CIRCUITS.find(r => r.practicalId === 1 && r.subExerciseId === 'bin2gray')!;
  const practical = PRACTICALS.find(p => p.id === 1)!;
  const sub = practical.subExercises!.find(s => s.id === 'bin2gray')!;
  const rows = sub.truthTable!.rows;

  it('correctly maps all 16 4-bit binary inputs to exact Gray code on output LEDs', () => {
    rows.forEach(([b3, b2, b1, b0, g3, g2, g1, g0]) => {
      // Switches: SW0=B0, SW1=B1, SW2=B2, SW3=B3
      const switches: (0 | 1)[] = [
        b0 as 0 | 1,
        b1 as 0 | 1,
        b2 as 0 | 1,
        b3 as 0 | 1,
        0, 0, 0, 0
      ];

      const res = runCircuitSimulation(
        ref.placedICs,
        ref.wires,
        switches,
        0, 0,
        true
      );

      expect(res.icPowerStatus[ref.placedICs[0].id]).toBe(true);
      expect(res.ledOutputs[3]).toBe(g3); // G3
      expect(res.ledOutputs[2]).toBe(g2); // G2
      expect(res.ledOutputs[1]).toBe(g1); // G1
      expect(res.ledOutputs[0]).toBe(g0); // G0
    });
  });
});

